#!/usr/bin/env node
// Grows a bare plane tree as pen strokes and writes it to art/_tree.svg.
// A thick trunk and three heavy limbs are drawn as two contours; from there each branch
// carries on as a leader and throws side shoots to alternating sides, as wood grows.
// Seeded, so the drawing is stable: node scripts/art/tree.mjs [seed]
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { random } from "./brush.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const rand = random(Number(process.argv[2] ?? 11));
const strokes = [];
const leaves = [];
const r = (n) => Math.round(n * 10) / 10;
const UP = -Math.PI / 2;

/** One limb drawn as two contours: a tapered body from (x,y) along a gentle curve. */
function limb(x, y, angle, length, w0, w1, bend) {
  const end = angle + bend;
  const mx = x + Math.cos(angle + bend / 2) * length / 2, my = y + Math.sin(angle + bend / 2) * length / 2;
  const ex = x + Math.cos(angle + bend / 2) * length * 0.5 + Math.cos(end) * length * 0.5;
  const ey = y + Math.sin(angle + bend / 2) * length * 0.5 + Math.sin(end) * length * 0.5;
  const n0 = [-Math.sin(angle), Math.cos(angle)], n1 = [-Math.sin(end), Math.cos(end)];
  const nm = [-Math.sin(angle + bend / 2), Math.cos(angle + bend / 2)];
  const side = (s, w) => [s * w / 2];
  for (const s of [-1, 1]) {
    const a = [x + n0[0] * side(s, w0), y + n0[1] * side(s, w0)];
    const m = [mx + nm[0] * side(s, (w0 + w1) / 2), my + nm[1] * side(s, (w0 + w1) / 2)];
    const b = [ex + n1[0] * side(s, w1), ey + n1[1] * side(s, w1)];
    // The shadow side (right, away from the light) gets the heavier pen
    strokes.push(`<path class="ink" data-w="${s > 0 ? 1.8 : 1.2}" data-taper="0.04 0.2" d="M${r(a[0])},${r(a[1])} Q${r(m[0])},${r(m[1])} ${r(b[0])},${r(b[1])}"/>`);
  }
  return { x: ex, y: ey, angle: end };
}

/** A branch as a single stroke that continues as a leader and throws side shoots. */
function branch(x, y, angle, length, width, depth, turn) {
  const bend = (rand() - 0.5) * 0.36;
  const end = angle + bend;
  const x1 = x + Math.cos(angle + bend / 2) * length * 0.5, y1 = y + Math.sin(angle + bend / 2) * length * 0.5;
  const x2 = x1 + Math.cos(end) * length * 0.5, y2 = y1 + Math.sin(end) * length * 0.5;
  const cls = width > 1.25 ? "ink" : "fine";
  strokes.push(`<path class="${cls}" data-w="${r(Math.max(0.55, width))}" data-taper="0.03 ${depth < 2 ? 0.75 : 0.3}" d="M${r(x)},${r(y)} Q${r(x1)},${r(y1)} ${r(x2)},${r(y2)}"/>`);
  if (depth === 0) {
    if (rand() < 0.16) leaves.push([x2, y2]);
    return;
  }
  // Leader: carries on, drifting a little toward the light and out
  branch(x2, y2, end + (UP - end) * 0.08 + (rand() - 0.5) * 0.2, length * (0.74 + rand() * 0.1), width * 0.76, depth - 1, -turn);
  // Side shoot, alternating sides, sometimes skipped so the crown stays open
  if (rand() < 0.82) {
    branch(x1, y1, angle + turn * (0.55 + rand() * 0.4), length * (0.55 + rand() * 0.15), width * 0.58, depth - 1, turn);
  }
}

// Trunk: wide at the root, leaning a little left, bark patches added below
const top = limb(1517, 768, UP - 0.03, 190, 30, 20, -0.06);
// Three heavy limbs from the fork
const left = limb(top.x - 4, top.y + 6, UP - 0.62, 92, 15, 9, -0.12);
const mid = limb(top.x, top.y + 2, UP - 0.06, 104, 14, 8, 0.08);
const right = limb(top.x + 5, top.y + 6, UP + 0.55, 80, 12, 7, 0.14);
branch(left.x, left.y, left.angle, 78, 4.4, 6, 1);
branch(mid.x, mid.y, mid.angle, 84, 4.2, 6, -1);
branch(right.x, right.y, right.angle, 70, 3.8, 6, 1);
const leafMarks = leaves.slice(0, 26).map(([x, y]) => {
  const a = rand() * Math.PI;
  const dx = Math.cos(a) * 3, dy = Math.sin(a) * 3;
  return `<path class="ink" data-w="2.4" data-taper="0.45 0.45" d="M${r(x - dx)},${r(y - dy)} L${r(x + dx)},${r(y + dy)}"/>`;
});

writeFileSync(join(root, "art", "_tree.svg"), `<svg viewBox="0 0 1600 900">
  <!-- Generated by scripts/art/tree.mjs: a bare plane tree in late October, a few last leaves. -->
  <g id="tree">
    <path class="fill" data-tone="paper" d="M1502,768 C1504,700 1506,640 1508,578 L1528,578 C1530,640 1532,700 1532,768 Z"/>
    <path class="fill" data-tone="bark" d="M1508,700 C1514,692 1526,694 1526,704 C1524,714 1510,714 1508,700 Z M1512,640 C1518,630 1528,634 1527,644 C1524,652 1514,652 1512,640 Z M1506,604 C1510,598 1518,600 1518,606 C1516,612 1508,612 1506,604 Z"/>
    <path class="hatch" data-angle="74" data-gap="3.4" data-w="0.45" d="M1520,766 C1520,710 1521,650 1522,590 L1529,590 C1530,650 1531,710 1532,766 Z"/>
    ${strokes.join("\n    ")}
    ${leafMarks.join("\n    ")}
  </g>
</svg>
`);
console.log(`tree: ${strokes.length} strokes, ${leafMarks.length} leaves`);
